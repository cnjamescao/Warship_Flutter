#!/usr/bin/env bash
# ================================================================
# tool/new_dart_file.sh —— 生成**符合注释规范**的 Dart 文件骨架
# ================================================================
# 存在理由：我（一线研发）在 v2.1 期间**连续两次**把文件头写错 ——
# 说明写成"靠记忆照抄"必然出错。注释规范守卫的判据是：
#   * 文件必须**以 `// ====` 开头**（第 1 行）；
#   * 从第 1 行到**下一个** `// ====` 之间，至少有 **3 行实质注释**；
#   * 也就是说：**两个分隔符，说明夹在中间** ——
#     不是"分隔符 + 标题 + 分隔符"（那样只有 1 行，不及格）。
#
# 用法：
#   bash tool/new_dart_file.sh lib/game/presentation/foo.dart "一句话标题" "所在层，如 Presentation 层"
#
# 生成后请**补全**"为什么存在 / 与谁交互 / 关键约束"，不要留着占位符。
# ================================================================
set -euo pipefail

if [ "$#" -lt 1 ]; then
  echo "用法：bash tool/new_dart_file.sh <目标路径> [标题] [架构层]" >&2
  exit 1
fi

TARGET="$1"
TITLE="${2:-（请填写一句话标题）}"
LAYER="${3:-（请填写架构层，如 Presentation 层）}"

if [ -e "$TARGET" ]; then
  echo "✗ 目标已存在：$TARGET（本脚本只用于新建）" >&2
  exit 1
fi

mkdir -p "$(dirname "$TARGET")"

# 注意：说明必须夹在**两个** `// ====` 之间，且 ≥3 行。
cat > "$TARGET" <<EOF
// ================================================================
// ${TARGET} —— ${TITLE}
//
// **架构位置**：${LAYER}。
//
// **为什么存在**：（请写清它解决什么问题、不解决什么问题）
//
// **与谁交互**：（上游 / 下游 / 数据流）
//
// **关键约束**：（不变量、时序、平台限制、易错点）
// ================================================================

EOF

echo "✓ 已生成：$TARGET"
echo "  请补全「为什么存在 / 与谁交互 / 关键约束」，并跑："
echo "    flutter analyze && flutter test test/architecture/comment_standard_test.dart"
